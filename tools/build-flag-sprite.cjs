/**
 * Composes every country flag into one PNG sprite sheet.
 *
 * Usage:
 *   npm run build-flag-sprite
 *
 * `flag-icons` ships 271 separate SVGs and a stylesheet of 271
 * `background-image: url(...)` rules. A background image loads lazily, so the
 * first time a driver from a country not already on screen is rendered, the
 * overlay fetches, parses and rasterises that country's SVG -- at the moment
 * the driver joins, which is exactly when the sim is busiest. Most are under a
 * kilobyte but rs.svg is 182 KB, sh-ac.svg 143 KB and bo.svg 103 KB.
 *
 * One sheet, decoded once at startup, costs nothing at join. This is the same
 * change already made for the LMU rank plates and the car-manufacturer logos,
 * and flags were the last per-row asset still loading one file at a time.
 *
 * Run under Electron for the same reason build-lmu-sprite.cjs is: nativeImage
 * reads PNG and JPEG but not SVG, so the rasterising happens in a hidden
 * window. The page is written to a temp file and loaded with loadFile, because
 * Chromium blocks top-level navigation to a `data:` URL.
 */

/* eslint-disable @typescript-eslint/no-require-imports --
 * An Electron main script, so CommonJS: `require('electron')` is how the main
 * process reaches the API, and an ESM entry would not get it.
 */
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { app, BrowserWindow } = require('electron');

const SOURCE_DIR = path.resolve('node_modules/flag-icons/flags/4x3');
const OUT_PNG = path.resolve('src/frontend/assets/img/country_flags.png');
const OUT_POSITIONS = path.resolve(
  'src/frontend/components/shared/CountryFlag/flagSpritePositions.ts'
);

/**
 * 4:3, matching the source set and the 1.333em-wide box the stylesheet used.
 * Doubled on the sheet so the art survives being drawn above its native size.
 */
const CELL_W = 32;
const CELL_H = 24;
const SCALE = 2;
const COLS = 17;

/** Long enough for 271 small rasterisations, short enough to not look hung. */
const TIMEOUT_MS = 120_000;

const fileUrl = (file) =>
  'file:///' + file.split(path.sep).join('/').replace(/ /g, '%20');

/** Built with path.sep rather than a backslash literal, which a shell ate.
 * `gb-eng.svg` -> `gb-eng`, which is the code the component already holds. */
const codeOf = (file) => path.basename(file, '.svg').toLowerCase();

const PAGE = `<!doctype html><meta charset="utf-8"><body><script>
window.compose = async ({ cells, cols, rows, cellW, cellH }) => {
  const canvas = document.createElement('canvas');
  canvas.width = cols * cellW;
  canvas.height = rows * cellH;
  const ctx = canvas.getContext('2d');
  ctx.imageSmoothingEnabled = true;
  ctx.imageSmoothingQuality = 'high';
  for (const cell of cells) {
    const image = await new Promise((resolve, reject) => {
      const img = new Image();
      img.onload = () => resolve(img);
      img.onerror = () => reject(new Error('could not load ' + cell.name));
      img.src = cell.url;
    });
    // Stretched to the cell, not fitted: every source is already 4:3, and a
    // flag with letterboxing would not match what the stylesheet drew.
    ctx.drawImage(image, cell.col * cellW, cell.row * cellH, cellW, cellH);
  }
  return canvas.toDataURL('image/png');
};
</script></body>`;

async function main() {
  if (!fs.existsSync(SOURCE_DIR)) {
    console.error(`flag-icons not found at ${SOURCE_DIR}`);
    return app.exit(1);
  }

  const files = fs
    .readdirSync(SOURCE_DIR)
    .filter((name) => name.toLowerCase().endsWith('.svg'))
    .sort();
  if (files.length === 0) {
    console.error('no SVGs in the flag directory');
    return app.exit(1);
  }

  const rows = Math.ceil(files.length / COLS);
  const cells = files.map((file, index) => ({
    name: codeOf(file),
    col: index % COLS,
    row: Math.floor(index / COLS),
    url: fileUrl(path.join(SOURCE_DIR, file)),
  }));

  const pageFile = path.join(os.tmpdir(), 'irdashies-flag-sprite.html');
  fs.writeFileSync(pageFile, PAGE, 'utf8');

  const win = new BrowserWindow({
    show: false,
    webPreferences: { nodeIntegration: false, contextIsolation: true },
  });
  await win.loadFile(pageFile);

  const dataUrl = await win.webContents.executeJavaScript(
    `window.compose(${JSON.stringify({
      cells,
      cols: COLS,
      rows,
      cellW: CELL_W * SCALE,
      cellH: CELL_H * SCALE,
    })})`,
    true
  );
  win.destroy();
  fs.rmSync(pageFile, { force: true });

  fs.writeFileSync(
    OUT_PNG,
    Buffer.from(dataUrl.replace(/^data:image\/png;base64,/, ''), 'base64')
  );

  fs.writeFileSync(
    OUT_POSITIONS,
    `// Generated by tools/build-flag-sprite.cjs. Do not edit by hand.
//
// Each entry is a country's [column, row] in country_flags.png. Keyed by the
// same lower-case ISO code the component already resolves, including the
// GB-XXX subdivisions.

export const FLAG_GRID = { cols: ${COLS}, rows: ${rows} } as const;

/** Source cell size, in the 4:3 the whole set shares. */
export const FLAG_CELL = { width: ${CELL_W}, height: ${CELL_H} } as const;

export const FLAG_POSITIONS: Record<string, readonly [number, number]> = {
${cells.map((c) => `  '${c.name}': [${c.col}, ${c.row}],`).join('\n')}
};
`
  );

  const kb = (fs.statSync(OUT_PNG).size / 1024).toFixed(0);
  console.log(
    `${OUT_PNG}\n  ${files.length} flags, ${COLS}x${rows} of ` +
      `${CELL_W * SCALE}x${CELL_H * SCALE} (${SCALE}x), ${kb} KB`
  );
  console.log(OUT_POSITIONS);
  app.exit(0);
}

app.whenReady().then(() => {
  const watchdog = setTimeout(() => {
    console.error(`timed out after ${TIMEOUT_MS}ms`);
    app.exit(1);
  }, TIMEOUT_MS);
  watchdog.unref?.();

  main().catch((error) => {
    console.error(error);
    app.exit(1);
  });
});
