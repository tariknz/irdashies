/**
 * Composes the LMU manufacturer logos into one sprite sheet.
 *
 * Usage:
 *   npm run build-lmu-manufacturer-sprite -- "C:/dev/my brandlogo"
 *
 * LMU and iRacing share some marques and not others -- Oreca, Duqueine,
 * Ginetta, Glickenhaus, Vanwall and Isotta Fraschini have no iRacing
 * equivalent -- so LMU gets its own sheet rather than extending the shared
 * one. Either can then be regenerated without disturbing the other, which is
 * the whole point of keeping them apart.
 *
 * Run under Electron rather than plain Node: the sources are ~512px logos that
 * have to land in 64px cells, three of them are odd sizes (500x500, 139x139,
 * 512x164), and scaling plus PNG encoding needs an image pipeline. Electron is
 * already a devDependency and ships one, where a dedicated image library would
 * be a new dependency for a build step run when the logos change.
 *
 * Composed with nativeImage in the main process -- no window and no GPU. An
 * offscreen BrowserWindow with a canvas was the obvious route and hung
 * indefinitely on this machine; cells do not overlap, so blitting rows of
 * BGRA into a cleared buffer needs no compositing anyway.
 *
 * Each logo is fitted inside its cell rather than stretched, so a wide mark
 * like Genesis keeps its proportions instead of being squashed square.
 */

/* eslint-disable @typescript-eslint/no-require-imports --
 * An Electron main script, so CommonJS: `require('electron')` is how the main
 * process reaches the API, and an ESM entry would not get it.
 */
const fs = require('node:fs');
const path = require('node:path');
const { app, nativeImage } = require('electron');

/** Matches the iRacing sheet, so both render at the same size in a row. */
const CELL = 64;
const COLS = 6;
/** BGRA, which is what nativeImage's bitmaps are. */
const BYTES_PER_PIXEL = 4;

const SOURCE_DIR = process.argv.slice(2).find((arg) => !arg.startsWith('-'));
const OUT_PNG = path.resolve(
  'src/frontend/assets/img/lmu_car_manufacturer.png'
);
const OUT_POSITIONS = path.resolve(
  'src/frontend/components/shared/CarManufacturer/lmuManufacturerSpritePositions.ts'
);

/** `Aston Martin.png` -> `astonmartin`, matching the existing slug style. */
const slugOf = (file) =>
  path
    .basename(file, '.png')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '');

function main() {
  if (!SOURCE_DIR || !fs.existsSync(SOURCE_DIR)) {
    console.error(`source directory not found: ${String(SOURCE_DIR)}`);
    return app.exit(1);
  }

  const files = fs
    .readdirSync(SOURCE_DIR)
    .filter((name) => name.toLowerCase().endsWith('.png'))
    .sort();
  if (files.length === 0) {
    console.error('no PNGs in the source directory');
    return app.exit(1);
  }

  const slugs = files.map(slugOf);
  const duplicates = slugs.filter((slug, i) => slugs.indexOf(slug) !== i);
  if (duplicates.length > 0) {
    console.error(`two logos share a slug: ${duplicates.join(', ')}`);
    return app.exit(1);
  }

  const rows = Math.ceil(files.length / COLS);
  const sheetW = COLS * CELL;
  const sheetH = rows * CELL;
  // Zeroed, so every pixel no logo covers stays transparent.
  const sheet = Buffer.alloc(sheetW * sheetH * BYTES_PER_PIXEL);

  const positions = [];
  files.forEach((file, index) => {
    const col = index % COLS;
    const row = Math.floor(index / COLS);
    positions.push({ slug: slugs[index], col, row });

    const source = nativeImage.createFromPath(path.join(SOURCE_DIR, file));
    if (source.isEmpty()) throw new Error(`could not read ${file}`);

    // Contain, not cover: a wide mark keeps its proportions and is centred in
    // the cell rather than cropped or stretched to a square.
    const { width, height } = source.getSize();
    const scale = Math.min(CELL / width, CELL / height);
    const scaled = source.resize({
      width: Math.max(1, Math.round(width * scale)),
      height: Math.max(1, Math.round(height * scale)),
      quality: 'best',
    });
    const size = scaled.getSize();
    const bitmap = scaled.toBitmap();

    const offsetX = col * CELL + Math.floor((CELL - size.width) / 2);
    const offsetY = row * CELL + Math.floor((CELL - size.height) / 2);
    for (let y = 0; y < size.height; y += 1) {
      const from = y * size.width * BYTES_PER_PIXEL;
      const to = ((offsetY + y) * sheetW + offsetX) * BYTES_PER_PIXEL;
      bitmap.copy(sheet, to, from, from + size.width * BYTES_PER_PIXEL);
    }
  });

  const composed = nativeImage.createFromBuffer(sheet, {
    width: sheetW,
    height: sheetH,
  });
  fs.writeFileSync(OUT_PNG, composed.toPNG());

  fs.writeFileSync(
    OUT_POSITIONS,
    `// Generated by tools/build-lmu-manufacturer-sprite.cjs. Do not edit by hand.
//
// LMU's own manufacturer sheet. Separate from the iRacing one because the two
// share only some marques, so either can be regenerated without the other.

export const LMU_SPRITES_PER_ROW = ${COLS};
export const LMU_SPRITES_PER_COLUMN = ${rows};

export const LMU_MANUFACTURER_SPRITE_POSITIONS: Record<
  string,
  { x: number; y: number }
> = {
${positions.map((p) => `  ${p.slug}: { x: ${p.col}, y: ${p.row} },`).join('\n')}
};
`
  );

  const size = fs.statSync(OUT_PNG).size;
  console.log(
    `${OUT_PNG}\n  ${files.length} logos, ${COLS}x${rows} of ${CELL}px, ` +
      `${(size / 1024).toFixed(0)} KB`
  );
  console.log(OUT_POSITIONS);
  console.log(`  ${positions.map((p) => p.slug).join(', ')}`);
  app.exit(0);
}

app.whenReady().then(() => {
  try {
    main();
  } catch (error) {
    console.error(error);
    app.exit(1);
  }
});
